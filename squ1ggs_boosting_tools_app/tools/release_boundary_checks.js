"use strict";
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
const app=process.argv[2] || path.resolve(__dirname,'..');
const restrict=require(path.join(app,'renderer/release_manifest_guard.js'));
const schema=require(path.join(app,'renderer/release_ui_schema.js'));
const live=JSON.parse(JSON.stringify(schema));
const vehicle=live.tabs.find(t=>t.id==='vehicle');
vehicle.sections.push({title:'Imported vehicles',fields:[{key:'vehicle_id',options:['warthog','furai'],option_labels:{warthog:'Halo Warthog'}}],actions:[{label:'Summon selected vehicle',action:'imported_vehicle_summon'}]});
vehicle.sections[0].actions.push({label:'Use on current vehicle',action:'imported_vehicle_use'});
const home=live.tabs.find(t=>t.id==='home');
home.sections.find(s=>Array.isArray(s.actions)).actions.push({label:'Private characters',action:'appearance_apply'});
live.tabs.push({id:'appearance',label:'Characters',sections:[]});
const clean=restrict(live,schema);
const text=JSON.stringify(clean);
for(const bad of ['Imported vehicles','warthog','furai','imported_vehicle','appearance_apply','Private characters']) assert(!text.includes(bad),bad);
assert(clean.tabs.find(t=>t.id==='vehicle').sections.some(s=>s.title==='Spawn vehicle'));
assert(text.includes('Clear map fog'));
assert(!JSON.stringify(restrict(clean,schema)).includes('warthog'));
assert.deepEqual(restrict(live,null),{tabs:[]});
const actions=require(path.join(app,'lib/release_actions.json'));
assert(!actions.some(a=>/appearance|imported_vehicle|imported_model/.test(a)));
assert(actions.includes('map_fog_unlock'));
assert(actions.includes('black_market'));
const main=fs.readFileSync(path.join(app,'main.js'),'utf8');
assert(main.includes('if (!releaseActions.has(String(action || "")))'));
assert(main.includes('manifest: restrictReleaseManifest(await fetchManifest(), releaseSchema)'));
console.log('PASS: live and cached nested menu injections removed; ordinary vehicle tools, Home fog and black market retained; unshipped actions blocked.');
