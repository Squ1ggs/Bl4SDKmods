"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const app = path.resolve(__dirname, "..");
const schema = require("../renderer/release_ui_schema.js");
const restrict = require("../renderer/release_manifest_guard.js");
const actions = require("../lib/release_actions.json");
const raw = JSON.parse(JSON.stringify(schema));
raw.tabs.find(t => t.id === "appearance").sections.push({title: "Foreign packs", actions: [{action: "imported_model_apply"}]});
raw.tabs.find(t => t.id === "vehicle").sections.push({title: "Imported vehicles", actions: [{action: "imported_vehicle_summon"}]});
raw.tabs.push({id: "private_test", sections: []});
const clean = restrict(raw, schema);
const text = JSON.stringify(clean);
assert(!/imported_model|imported_vehicle|Foreign packs|private_test/.test(text));
assert(text.includes("appearance_apply_selected"));
assert(text.includes("Clear map fog"));
assert(text.includes("black_market"));
assert.deepEqual(clean.tabs.slice(0, 3).map(t => t.id), ["home", "builds", "auto_lobby"]);
assert(clean.tabs.find(t => t.id === "appearance").sections[0].multiselect.singleSelect);
assert(!actions.some(a => /imported_model|imported_vehicle/.test(a)));
assert(actions.includes("appearance_apply_selected"));
assert(actions.includes("appearance_restore"));
assert.deepEqual(restrict(raw, null), {tabs: []});
const main = fs.readFileSync(path.join(app, "main.js"), "utf8");
assert(main.includes('if (!releaseActions.has(String(action || "")))'));
assert(main.includes("restrictReleaseManifest(await fetchManifest(), releaseSchema)"));
const renderer = fs.readFileSync(path.join(app, "renderer/app.js"), "utf8");
assert(renderer.includes("pollAppearanceApply(code, data.appearance?.operation_id"));
assert(renderer.includes("Number(appearance.operation_id) !== Number(operationId)"));
assert(actions.includes("appearance_preview_selected"));
assert(actions.includes("appearance_clear_previews"));
assert(renderer.includes("function resolvePictureFinalLevel()"));
console.log("PASS: native appearance retained; imported/vehicle menu injection blocked; first-release fixes and tab order retained.");
